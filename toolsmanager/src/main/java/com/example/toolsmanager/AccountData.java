package com.example.toolsmanager;

public class AccountData {
  private String username;
  private String password;

  void setUsername(String name) {
    username = name;
  }

  void setPassword(String pass) {
    password = pass;
  }

  String getUsername() {
    return username;
  }

  String getPassword() {
    return password;
  }
}
